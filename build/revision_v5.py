def resolve(f):
    p = MS / f
    return p if p.exists() else ROOT / f


def main():
    check_only = '--check' in sys.argv

    by_file = {}
    for f, lab, old, new in EDITS + DROP_BLOCKS:
        by_file.setdefault(f, []).append((lab, old, new))

    # ---- 阶段一：全量校验（一个字节都不写） ----
    contents, bad = {}, []
    for f in sorted(by_file):
        p = resolve(f)
        s = io.open(p, encoding='utf-8').read()
        contents[f] = s
        for lab, old, new in by_file[f]:
            c = s.count(old)
            if c != 1:
                bad.append((f, lab, c))
    if bad:
        for f, lab, c in bad:
            print('FAIL %-28s %-34s count=%d' % (f, lab, c))
        raise SystemExit('中止：%d 条未唯一命中，未写入任何文件' % len(bad))

    print('校验通过：%d 个文件 / %d 条修订全部唯一命中'
          % (len(by_file), sum(len(v) for v in by_file.values())))
    if check_only:
        for f in sorted(by_file):
            for lab, _, _ in by_file[f]:
                print('  OK %-28s %s' % (f, lab))
        return

    # ---- 阶段二：统一写入 ----
    total = 0
    for f in sorted(by_file):
        s = contents[f]
        for lab, old, new in by_file[f]:
            s = s.replace(old, new)
            total += 1
        io.open(resolve(f), 'w', encoding='utf-8').write(s)
        print('WROTE %-28s %d 处' % (f, len(by_file[f])))
    print('DONE %d edits across %d files' % (total, len(by_file)))


if __name__ == '__main__':
    main()
